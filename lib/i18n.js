function normalizeLanguage(language) {
  return language === 'de' ? 'de' : 'en';
}

function normalizeText(text) {
  return String(text).replace(/\s+/g, ' ').trim();
}

function translate(text, language) {
  if (text === undefined || text === null) {
    return '';
  }

  const normalized_language = normalizeLanguage(language);

  if (normalized_language === 'en') {
    return text;
  }

  return String(text).split('=====').map(part => {
    const phrase = part.trim();
    if (!phrase) {
      return part;
    }

    const leading = part.slice(0, part.length - part.trimStart().length);
    const trailing = part.slice(part.trimEnd().length);
    const normalized_phrase = normalizeText(phrase);
    const dynamic_translation = dynamic_translations.find(([pattern]) => pattern.test(normalized_phrase));

    return leading
      + (german[normalized_phrase]
        || (dynamic_translation && normalized_phrase.replace(dynamic_translation[0], dynamic_translation[1]))
        || phrase)
      + trailing;
  }).join('=====');
}

function hasTranslation(text, language) {
  if (normalizeLanguage(language) === 'en') {
    return true;
  }

  return String(text)
    .split('=====')
    .every(part => {
      const phrase = normalizeText(part);
      return !phrase
        || Object.prototype.hasOwnProperty.call(german, phrase)
        || dynamic_translations.some(([pattern]) => pattern.test(phrase));
    });
}

