function normalizeLanguage(language) {
  return language_codes.has(language) ? language : 'en';
}

function detectBrowserLanguage(accept_language) {
  if (typeof accept_language !== 'string') {
    return 'en';
  }

  const preferences = accept_language.split(',').map((preference, index) => {
    const [range, ...parameters] = preference.trim().split(';');
    const quality_parameter = parameters.find(parameter => /^\s*q=/i.test(parameter));
    const quality = quality_parameter
      ? Number(quality_parameter.split('=')[1])
      : 1;

    return {
      code: range.split('-')[0].toLowerCase(),
      index,
      quality: Number.isFinite(quality) && quality >= 0 && quality <= 1 ? quality : 0,
    };
  })
    .filter(preference => preference.quality > 0)
    .sort((left, right) => right.quality - left.quality || left.index - right.index);

  const supported_preference = preferences.find(preference => language_codes.has(preference.code));
  return supported_preference ? supported_preference.code : 'en';
}

function normalizeText(text) {
  return String(text).replace(/\s+/g, ' ').trim();
}

function translate(text, language) {
  if (text === undefined || text === null) {
    return '';
  }

  const normalized_language = normalizeLanguage(language);

  if (normalized_language === 'en') {
    return text;
  }

  const catalog = normalized_language === 'de' ? german : korean;
  const dynamic_catalog = normalized_language === 'de'
    ? dynamic_translations
    : korean_dynamic_translations;

  return String(text).split('=====').map(part => {
    const phrase = part.trim();
    if (!phrase) {
      return part;
    }

    const leading = part.slice(0, part.length - part.trimStart().length);
    const trailing = part.slice(part.trimEnd().length);
    const normalized_phrase = normalizeText(phrase);
    const dynamic_translation = dynamic_catalog.find(([pattern]) => pattern.test(normalized_phrase));

    return leading
      + (catalog[normalized_phrase]
        || (dynamic_translation && normalized_phrase.replace(dynamic_translation[0], dynamic_translation[1]))
        || phrase)
      + trailing;
  }).join('=====');
}

function hasTranslation(text, language) {
  const normalized_language = normalizeLanguage(language);
  if (normalized_language === 'en') {
    return true;
  }

  const catalog = normalized_language === 'de' ? german : korean;
  const dynamic_catalog = normalized_language === 'de'
    ? dynamic_translations
    : korean_dynamic_translations;

  return String(text)
    .split('=====')
    .every(part => {
      const phrase = normalizeText(part);
      return !phrase
        || Object.prototype.hasOwnProperty.call(catalog, phrase)
        || dynamic_catalog.some(([pattern]) => pattern.test(phrase));
    });
}

